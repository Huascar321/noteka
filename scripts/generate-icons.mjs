import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { restingAttributes } from '@animateicons/vanilla';
import { ICON_SELECTION, SIDEBAR_ICON_NAMES } from './icon-catalog.mjs';
const check = process.argv.includes('--check');
const packageInfo = JSON.parse(await readFile(new URL('../node_modules/@animateicons/vanilla/package.json', import.meta.url), 'utf8'));
if (packageInfo.version !== '0.1.0') throw new Error('Revisá catálogo/licencias antes de cambiar AnimateIcons 0.1.0');
const libraries = {huge: await import('@animateicons/vanilla/huge'), lucide: await import('@animateicons/vanilla/lucide')};
const tags = new Set(['path','circle','ellipse','line','polyline','polygon','rect','g','defs','mask','clipPath']);
const escape = s => String(s).replaceAll('&','&amp;').replaceAll('"','&quot;').replaceAll('<','&lt;');
function attributes(node, root = false) {
  const attrs = restingAttributes(node, root, '__NOTEKA_ICON_SCOPE__');
  for (const [key,value] of Object.entries(attrs)) {
    if (!/^[a-zA-Z][a-zA-Z0-9:-]*$/.test(key) || /^on/i.test(key) || /(?:javascript:|https?:|<)/i.test(value) && key !== 'xmlns') throw new Error(`Atributo SVG inválido: ${key}`);
    if (key === 'href' && !value.startsWith('#')) throw new Error('Referencia SVG no local');
  }
  return attrs;
}
function element(node) {
  if (!tags.has(node.tag)) throw new Error(`Tag SVG no permitido: ${node.tag}`);
  return `<${node.tag}${Object.entries(attributes(node)).map(([key,value])=>` ${key}="${escape(value)}"`).join('')}>${(node.children??[]).map(element).join('')}</${node.tag}>`;
}
const assets=[], indices={}, keys={}, defs={};
for (const [key,[library,name]] of Object.entries(ICON_SELECTION)) {
  const data = libraries[library][name];
  if (!data || data.tag !== 'svg' || data.library !== library) throw new Error(`Icono ausente ${library}/${name}`);
  const source = `${library}/${data.name}`;
  if (!(source in indices)) {indices[source]=assets.length;assets.push({attrs:attributes(data,true),body:(data.children??[]).map(element).join('')});}
  keys[key]=indices[source];defs[key]={data,library,name};
}
const header='// Generated by scripts/generate-icons.mjs from @animateicons/vanilla 0.1.0.\n// Local SVG assets; upstream licenses: third-party/animateicons/. Do not edit.\n';
const staticSource=header+'export type StaticIcon = { attrs: Record<string, string>; body: string };\nconst ASSETS: StaticIcon[] = '+JSON.stringify(assets)+';\nexport const ICONS = {\n'+Object.entries(keys).map(([key,index])=>`  ${JSON.stringify(key)}: ASSETS[${index}],`).join('\n')+'\n};\n';
const navSource=header+"import type { IconData } from '@animateicons/vanilla';\n"+SIDEBAR_ICON_NAMES.map((key,i)=>{const {data,library,name}=defs[key];return `import { ${name} as icon${i} } from '@animateicons/vanilla/${library}/${data.name}';`;}).join('\n')+'\nexport const SIDEBAR_ICONS: Record<string, IconData> = {\n'+SIDEBAR_ICON_NAMES.map((key,i)=>`  ${JSON.stringify(key)}: icon${i},`).join('\n')+'\n};\n';
const outputs = [['../src/lib/icons.generated.ts',staticSource],['../src/lib/sidebar-icons.generated.ts',navSource]];
for (const name of ['LICENSE','THIRD_PARTY_NOTICES.md']) {
  const notice = await readFile(new URL(`../node_modules/@animateicons/vanilla/${name}`,import.meta.url),'utf8');
  outputs.push([`../third-party/animateicons/${name}`,notice]);
  outputs.push([`../public/licenses/animateicons/${name === 'LICENSE' ? 'LICENSE.txt' : 'THIRD_PARTY_NOTICES.txt'}`,notice]);
}
for (const [path,source] of outputs) {
  const url=new URL(path,import.meta.url);
  if (check) {if (await readFile(url,'utf8') !== source) throw new Error(`Catálogo desactualizado: npm run icons:generate (${path})`);}
  else { await mkdir(dirname(fileURLToPath(url)), {recursive:true}); await writeFile(url,source); }
}
console.log(`${check?'Vigentes':'Generados'} ${Object.keys(keys).length} iconos SVG (${assets.length} formas únicas); ${SIDEBAR_ICON_NAMES.length} definiciones laterales diferidas.`);
